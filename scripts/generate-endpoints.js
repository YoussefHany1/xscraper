// Reads accounts from config.js and writes one API endpoint per account into
// api/tweets/<Username>.js. Stale endpoints (accounts removed from config.js)
// are deleted. Run after editing the accounts list:
//
//   npm run generate

const fs = require("fs");
const path = require("path");

const { listAccounts, isValidUsername } = require("../lib/config");

const ROOT_DIR = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT_DIR, "api", "tweets");
const HEADER = "// AUTO-GENERATED by scripts/generate-endpoints.js -- do not edit by hand.\n// Regenerate with `npm run generate` after changing accounts in config.js.\n";

function render(username) {
  const endpoint = `/api/tweets/${username}`;
  return `${HEADER}
// GET ${endpoint}
const { handleTweets } = require("../../lib/handler");

module.exports = function handler(req, res) {
  return handleTweets(req, res, { account: ${JSON.stringify(username)} });
};

module.exports.config = { maxDuration: 120 };
`;
}

function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const accounts = listAccounts();
  const valid = accounts.filter(isValidUsername);
  const rejected = accounts.filter((a) => !isValidUsername(a));

  const expected = new Set(valid.map((a) => `${a}.js`));
  let written = 0;

  for (const username of valid) {
    const file = path.join(OUT_DIR, `${username}.js`);
    const next = render(username);
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (current !== next) {
      fs.writeFileSync(file, next);
      written++;
    }
  }

  // Drop endpoints for accounts that are no longer configured.
  let removed = 0;
  for (const name of fs.readdirSync(OUT_DIR)) {
    if (!name.endsWith(".js")) continue;
    if (name === "[account].js" || expected.has(name)) continue;
    fs.rmSync(path.join(OUT_DIR, name));
    removed++;
  }

  console.log(`${valid.length} account endpoint(s) in api/tweets/ (${written} written, ${removed} removed)`);
  for (const username of valid) console.log(`  /api/tweets/${username}`);
  if (rejected.length) {
    console.log(`\nSkipped invalid username(s): ${rejected.join(", ")}`);
  }
}

main();